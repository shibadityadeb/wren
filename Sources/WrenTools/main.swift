import AppKit
import WrenKit

/// Dev-only tool.
///   wren-tools trace <logo.png> <out.swift>   trace the bird into WrenMarkData.swift
///   wren-tools assets <logo.png> <dir>        write SVGs, iconset, previews from the logo + trace
let args = CommandLine.arguments
func usage() -> Never { print("usage: wren-tools trace <logo.png> <out.swift> | assets <logo.png> <dir> | snapshot <dir>"); exit(2) }
if args.count == 3 && args[1] == "snapshot" {
    let app = NSApplication.shared
    app.setActivationPolicy(.prohibited)
    try MainActor.assumeIsolated { try SnapshotRenderer.renderAll(to: URL(fileURLWithPath: args[2])) }
    print("wrote snapshots to \(args[2])")
    exit(0)
}
guard args.count >= 4 else { usage() }
let logoURL = URL(fileURLWithPath: args[2])
let out = URL(fileURLWithPath: args[3])
let logo = try LogoSource(url: logoURL)

func svg(_ path: CGPath, fill: String, background: String? = nil) -> String {
    let b = WrenMark.bounds.insetBy(dx: -4, dy: -4)
    let vb = String(format: "%.2f %.2f %.2f %.2f", b.minX, b.minY, b.width, b.height)
    let bg = background.map { #"<rect x="\#(b.minX)" y="\#(b.minY)" width="\#(b.width)" height="\#(b.height)" fill="\#($0)"/>"# } ?? ""
    return #"<svg xmlns="http://www.w3.org/2000/svg" viewBox="\#(vb)">\#(bg)<path fill="\#(fill)" fill-rule="evenodd" d="\#(WrenMark.svgPathData(path))"/></svg>"# + "\n"
}

switch args[1] {
case "trace":
    let contours = try logo.traceBird()
    func lit(_ pts: [CGPoint]) -> String {
        "[" + pts.map { String(format: "%.2f,%.2f", $0.x, $0.y) }.joined(separator: ",") + "]"
    }
    let outlines = contours.filter { !$0.isHole }.map { lit($0.points) }
    let holes = contours.filter { $0.isHole }.map { lit($0.points) }
    let pointCount = contours.map { $0.points.count }.reduce(0, +)
    let src = """
    // Generated by `wren-tools trace \(logoURL.lastPathComponent)`. Do not edit by hand.
    // Vector trace of the bird in assets/logo.png (Vision contour detection).
    // \(outlines.count) outline(s), \(holes.count) hole(s), \(pointCount) points.
    extension WrenMark {
        static let outlines: [[Double]] = [
            \(outlines.joined(separator: ",\n        "))
        ]
        static let holes: [[Double]] = [
            \(holes.joined(separator: ",\n        "))
        ]
    }

    """
    try src.write(to: out, atomically: true, encoding: .utf8)
    print("tile \(logo.tile), interior \(logo.interior), radius \(Int(logo.cornerRadius)), cream \(logo.creamHex)")
    print("traced \(outlines.count) outlines, \(holes.count) holes, \(pointCount) points")

case "assets":
    guard !WrenMark.path.isEmpty else { print("run `trace` first, then rebuild"); exit(1) }
    let fm = FileManager.default
    try fm.createDirectory(at: out, withIntermediateDirectories: true)
    let cream = logo.creamHex
    try svg(WrenMark.path, fill: "#000000").write(to: out.appendingPathComponent("wren-mark.svg"), atomically: true, encoding: .utf8)
    try svg(WrenMark.path, fill: cream).write(to: out.appendingPathComponent("wren-mark-light.svg"), atomically: true, encoding: .utf8)
    try svg(WrenMark.path, fill: "#000000", background: cream).write(to: out.appendingPathComponent("wren-mark-on-cream.svg"), atomically: true, encoding: .utf8)
    try svg(WrenMark.path, fill: cream, background: "#1C1C1A").write(to: out.appendingPathComponent("wren-mark-on-charcoal.svg"), atomically: true, encoding: .utf8)
    try svg(WrenMark.compactPath, fill: "#000000").write(to: out.appendingPathComponent("wren-menubar-template.svg"), atomically: true, encoding: .utf8)

    let iconset = out.appendingPathComponent("Wren.iconset")
    try? fm.removeItem(at: iconset)
    for base in [16, 32, 128, 256, 512] {
        for scale in [1, 2] {
            let name = scale == 1 ? "icon_\(base)x\(base).png" : "icon_\(base)x\(base)@2x.png"
            try IconRenderer.writePNG(logo.appIcon(size: base * scale)!, to: iconset.appendingPathComponent(name))
        }
    }
    try IconRenderer.writePNG(logo.appIcon(size: 1024)!, to: out.appendingPathComponent("app-icon-1024.png"))

    let black = NSColor.black.cgColor
    let creamC = NSColor(srgbRed: 251 / 255, green: 245 / 255, blue: 228 / 255, alpha: 1).cgColor
    let charcoal = NSColor(srgbRed: 0.11, green: 0.11, blue: 0.10, alpha: 1).cgColor
    let previews = out.appendingPathComponent("previews")
    try? fm.removeItem(at: previews)
    for px in [16, 18, 22, 32, 36, 64] {
        try IconRenderer.writePNG(IconRenderer.markPreview(size: px, foreground: black, background: creamC)!, to: previews.appendingPathComponent("mark-light-\(px).png"))
        try IconRenderer.writePNG(IconRenderer.markPreview(size: px, foreground: creamC, background: charcoal)!, to: previews.appendingPathComponent("mark-dark-\(px).png"))
    }
    for px in [16, 32, 64] {
        try IconRenderer.writePNG(logo.appIcon(size: px)!, to: previews.appendingPathComponent("icon-\(px).png"))
    }
    print("wrote assets to \(out.path)")

default:
    usage()
}
